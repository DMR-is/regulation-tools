/*
  How the editors take a text in and hand it back out: shared by `Editor`
  (TinyMCE) and `EditorV2`, moved here unchanged from Editor.tsx.
*/

import { HTMLText } from './types';
import { asDiv, document_base_url, typeAttrToStyleValueMap } from './utils';

// ---------------------------------------------------------------------------

const stripLocalBaseUrlHost = (root: ReturnType<typeof asDiv>): string => {
  const baseUrlLength = document_base_url.length;
  root.qq(`img[src^="${document_base_url}"]`).forEach((elm) => {
    elm.setAttribute(
      'src',
      (elm.getAttribute('src') as string).substring(baseUrlLength),
    );
  });
  root.qq(`a[href^="${document_base_url}"]`).forEach((elm) => {
    elm.setAttribute(
      'href',
      (elm.getAttribute('href') as string).substring(baseUrlLength),
    );
  });
  return root.innerHTML;
};

// ---------------------------------------------------------------------------

/** Replaced/void elements that constitute real content. HTML containing any
 * of these is never "empty", regardless of whether void tags are serialized
 * self-closed (`<img />`) or not (`<img>`) — a DOM round-trip drops the slash,
 * which would otherwise make the open-tag regex below strip them away. */
const NON_EMPTY_ELEMENTS = /<(?:img|hr|svg)[\s/>]/i;

/* Replace empty HTML with empty string ('') */
const _stripEmpty = (html: HTMLText) =>
  html.length > 1000 || NON_EMPTY_ELEMENTS.test(html)
    ? html // assume large HTML (or HTML with real content elements) is never empty
    : (html
        // check for any number of non-self-closing html open tags
        // immediately followed by any number of closing html tags
        // with only spaces between or around them.
        // This pattern is the type of HTML typically leftover
        // in TinyMCE when a user selects all and hits delete.
        .replace(/^(<(?!\/)[^>]*[^/>]>)+(<\/[^>]+>)+$/, '') as HTMLText);

/**
 * `asStyles` turns `align` and list `type` attributes into styles, which
 * TinyMCE needed. EditorV2 reads the attributes as they are, and passes
 * `false`.
 */
export const importText = (text: HTMLText, asStyles = true): HTMLText => {
  if (typeof document === 'undefined') {
    return text;
  }
  const root = asDiv(text);
  asStyles &&
    root.qq<HTMLElement & { align: string }>('[align]').forEach((elm) => {
      elm.style.textAlign = elm.align;
      elm.removeAttribute('align');
    });
  asStyles &&
    root
      .qq<HTMLUListElement | HTMLOListElement | HTMLLIElement>(
        'ol[type], ul[type], li[type]',
      )
      .forEach((elm) => {
        elm.style.listStyleType = typeAttrToStyleValueMap[
          elm.getAttribute('type') as string
        ] as string;
        elm.removeAttribute('type');
      });
  // fyrsta útgáfa af dirtyClean vistaði Undirritun1 og Undirritun2
  root.qq('.Undirritun1, .Undirritun2').forEach((elm) => {
    elm.className = 'Undirritun';
  });

  // root.qq('[data-autogenerated]').forEach((elm) => {
  //   elm.setAttribute('data-autogenerated', 'true');
  // });
  // root.qq('table.layout.layout--list').forEach((elm) => {
  //   elm.classList.remove('layout');
  // });
  return _stripEmpty(root.innerHTML as HTMLText);
};

export const exportText = (text: HTMLText): HTMLText => {
  const root = asDiv(text);
  stripLocalBaseUrlHost(root);
  // root.qq('[data-autogenerated="false"]').forEach((elm) => {
  //   elm.removeAttribute('data-autogenerated');
  // });
  return _stripEmpty(root.innerHTML as HTMLText);
};
