/**
 * The attributes the schema keeps, by element: `true` for all of them
 * (event handlers aside, and a cell's alignment only as `ALIGNMENTS`; see
 * `lostTableAttributes`), else their names. `style` stands for the
 * properties in `KEPT_STYLES`. Elements not listed are either dropped whole
 * (and reported as such) or passed over (`PASSED_OVER`). Pinned against the
 * schema in src/__test__/editorV2.test.ts.
 */
const BLOCK = ['id', 'data-autogenerated'];
const ALIGN = ['align', 'style'];
const HEADING = [...BLOCK, ...ALIGN, 'class'];
const KEPT_ATTRIBUTES: Record<string, true | Array<string>> = {
  P: [...BLOCK, ...ALIGN, 'class'],
  H1: HEADING,
  H2: HEADING,
  H3: HEADING,
  H4: HEADING,
  H5: HEADING,
  H6: HEADING,
  BLOCKQUOTE: BLOCK,
  HR: BLOCK,
  OL: [...BLOCK, 'start', 'type'],
  UL: [...BLOCK, 'start', 'type'],
  LI: [...BLOCK, 'value'],
  TABLE: true,
  COLGROUP: true,
  COL: true,
  TR: true,
  TD: true,
  TH: true,
  THEAD: [],
  TBODY: [],
  TFOOT: [],
  IMG: [...BLOCK, 'src', 'alt', 'title', 'width', 'height'],
  A: ['id', 'href', 'target', 'rel', 'class', 'title'],
  STRONG: ['id'],
  B: ['id'],
  EM: ['id'],
  I: ['id'],
  U: ['id'],
  S: [],
  STRIKE: [],
  DEL: [],
  SUB: ['id'],
  SUP: ['id', 'class'],
  BR: [],
};
const KEPT_STYLES: Record<string, Array<string>> = {
  P: ['margin-left', 'text-indent', 'text-align'],
};
const ALIGNMENTS = ['left', 'center', 'right', 'justify'];
/** The structural titles, which keep `class` and (but for appendix) no alignment. */
const TITLE_CLASSES: Record<string, Array<string>> = {
  H2: [
    'chapter__title',
    'subchapter__title',
    'section__title',
    'appendix__title',
  ],
  H3: ['article__title', 'article__title article__title--provisional'],
};

type Lost = { key: string; example: string };

/** The attributes of `elm` the editor would drop. */
/**
 * What a table element drops: event handlers, and on a cell an alignment
 * other than `ALIGNMENTS` (its `text-align` is the cell's alignment).
 */
const lostTableAttributes = (elm: Element, lost: Array<Lost>) => {
  const tag = elm.tagName.toLowerCase();
  const isCell = tag === 'td' || tag === 'th';
  const isAlignment = (value: string) =>
    ALIGNMENTS.includes(value.trim().toLowerCase());
  for (const { name, value } of Array.from(elm.attributes)) {
    if (
      isEventHandler(name) ||
      (isCell && name === 'align' && !isAlignment(value))
    ) {
      lost.push({
        key: `${tag} ${name}`,
        example: `<${tag} ${name}="${value}">`,
      });
    } else if (isCell && name === 'style') {
      value.split(';').forEach((decl) => {
        const [property, align = ''] = decl.split(':');
        property!.trim().toLowerCase() === 'text-align' &&
          !isAlignment(align) &&
          lost.push({
            key: `${tag} style text-align`,
            example: `<${tag} style="${decl.trim()}">`,
          });
      });
    }
  }
};

const lostAttributes = (elm: Element, lost: Array<Lost>) => {
  let kept = KEPT_ATTRIBUTES[elm.tagName];
  if (!kept || elm.attributes.length === 0) {
    return;
  }
  if (kept === true) {
    lostTableAttributes(elm, lost);
    return;
  }
  if (elm.tagName === 'A' && !elm.hasAttribute('href')) {
    kept = ['id']; // an anchor, not a link
  }
  const tag = elm.tagName.toLowerCase();
  const titleClass = (elm.getAttribute('class') || '')
    .trim()
    .replace(/\s+/g, ' ');
  const isTitle = !!TITLE_CLASSES[elm.tagName]?.includes(titleClass);
  const alignable = !isTitle || titleClass === 'appendix__title';
  const styles = !kept.includes('style')
    ? []
    : (KEPT_STYLES[elm.tagName] || ['text-align']).filter(
        (property) => alignable || property !== 'text-align',
      );
  for (const { name, value } of Array.from(elm.attributes)) {
    if (name === 'style') {
      value.split(';').forEach((decl) => {
        const property = decl.split(':')[0]!.trim().toLowerCase();
        property &&
          !styles.includes(property) &&
          lost.push({
            key: `${tag} style ${property}`,
            example: `<${tag} style="${decl.trim()}">`,
          });
      });
    } else if (
      !kept.includes(name) ||
      (name === 'align' &&
        (!alignable || !ALIGNMENTS.includes(value.trim().toLowerCase()))) ||
      (name === 'class' && /^H\d$/.test(elm.tagName) && !isTitle)
    ) {
      lost.push({
        key: `${tag} ${name}`,
        example: `<${tag} ${name}="${value}">`,
      });
    }
  }
};

/** One line per element and attribute (style: property), with a count. */
const summarize = (lost: Array<Lost>): Array<string> => {
  const counts = new Map<string, { example: string; count: number }>();
  lost.forEach(({ key, example }) => {
    const entry = counts.get(key);
    entry ? entry.count++ : counts.set(key, { example, count: 1 });
  });
  return Array.from(counts.values(), ({ example, count }) =>
    count > 1 ? `${example} (${count}×)` : example,
  );
};

/**
 * What in `html` the editor would drop on load, as short HTML snippets:
 * elements, then attributes (one line per element and attribute, with an
 * example and a count); empty when the text loads whole. For the warning in
 * the browser, where the full check (which needs cleanup, and so jsdom)
 * cannot run.
 */
export const findUnsupportedElements = (html: string): Array<string> => {
  unsupported = [];
  const root = elementFromString(editorInput(html));
  DOMParser.fromSchema(checkSchema).parse(root);
  const lost: Array<Lost> = [];
  root.querySelectorAll('*').forEach((elm) => lostAttributes(elm, lost));
  return [...unsupported, ...summarize(lost)];
};
