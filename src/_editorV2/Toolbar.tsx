/*
  EditorV2's toolbar. It subscribes only to the state it shows (active
  marks, block format, alignment, list, whether the selection is in a
  table), so typing does not re-render it on every keystroke.
*/

import React, { ReactNode, useEffect, useId, useRef, useState } from 'react';
import { Editor, useEditorState } from '@tiptap/react';
import {
  AlignCenter,
  AlignLeft,
  AlignRight,
  BadgeCheck,
  Bold,
  ChevronDown,
  Code,
  FileText,
  Image,
  Italic,
  Link,
  List,
  ListOrdered,
  Minus,
  Omega,
  Redo2,
  RemoveFormatting,
  Search,
  Strikethrough,
  Subscript,
  Superscript,
  Table,
  Underline,
  Undo2,
} from 'lucide-react';

import {
  atTopLevel,
  BLOCK_FORMATS,
  BlockFormat,
  clearAutogenerated,
  currentBlockFormat,
  inAutogenerated,
  setBlockFormat,
} from './extensions';
import { GROUPS, ToolbarItem } from './toolbarItems';

export type DialogName = 'link' | 'charmap' | 'code' | 'searchreplace';

export type ToolbarActions = {
  openDialog: (name: DialogName) => void;
  insertImage: () => void;
  importWord: () => void;
};

const ICON_SIZE = 18;

// ---------------------------------------------------------------------------

const Button = (props: {
  label: string;
  icon: ReactNode;
  active?: boolean;
  disabled?: boolean;
  onClick: () => void;
}) => (
  <button
    type="button"
    className={
      'regtools-toolbar__button' +
      (props.active ? ' regtools-toolbar__button--active' : '')
    }
    title={props.label}
    aria-label={props.label}
    aria-pressed={props.active}
    disabled={props.disabled}
    // Keeps the editor's selection while clicking.
    onMouseDown={(e) => e.preventDefault()}
    onClick={props.onClick}
  >
    {props.icon}
  </button>
);

/**
 * A button showing a list of buttons below it (the disclosure pattern: plain
 * buttons, reached with Tab). Escape closes it and returns focus to the
 * button; so does moving focus or clicking elsewhere.
 */
const Dropdown = (props: {
  label: string;
  icon: ReactNode;
  active?: boolean;
  disabled?: boolean;
  children: ReactNode;
}) => {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);
  const trigger = useRef<HTMLButtonElement>(null);
  const id = useId();
  useEffect(() => {
    if (!open) {
      return;
    }
    const close = (e: MouseEvent) => {
      if (!ref.current?.contains(e.target as Node)) {
        setOpen(false);
      }
    };
    document.addEventListener('mousedown', close);
    return () => document.removeEventListener('mousedown', close);
  }, [open]);
  useEffect(() => {
    props.disabled && setOpen(false);
  }, [props.disabled]);
  return (
    <div
      className="regtools-toolbar__dropdown"
      ref={ref}
      onKeyDown={(e) => {
        if (open && e.key === 'Escape') {
          e.stopPropagation();
          setOpen(false);
          trigger.current?.focus();
        }
      }}
      onBlur={(e) => {
        if (open && !ref.current?.contains(e.relatedTarget as Node | null)) {
          setOpen(false);
        }
      }}
    >
      <button
        ref={trigger}
        type="button"
        className={
          'regtools-toolbar__button' +
          (props.active ? ' regtools-toolbar__button--active' : '')
        }
        title={props.label}
        aria-label={props.label}
        aria-expanded={open}
        aria-controls={id}
        disabled={props.disabled}
        onMouseDown={(e) => e.preventDefault()}
        onClick={() => setOpen(!open)}
      >
        {props.icon}
        <ChevronDown size={12} aria-hidden />
      </button>
      {open && (
        <div
          id={id}
          className="regtools-toolbar__menu"
          onClick={() => setOpen(false)}
        >
          {props.children}
        </div>
      )}
    </div>
  );
};

/** A choice in a dropdown. `active` (a state, like the current format) is
 * announced with `aria-pressed`; actions leave it out. */
const MenuItem = (props: {
  label: string;
  disabled?: boolean;
  active?: boolean;
  onClick: () => void;
}) => (
  <button
    type="button"
    className={
      'regtools-toolbar__menuitem' +
      (props.active ? ' regtools-toolbar__menuitem--active' : '')
    }
    aria-pressed={props.active}
    disabled={props.disabled}
    onMouseDown={(e) => e.preventDefault()}
    onClick={props.onClick}
  >
    {props.label}
  </button>
);

