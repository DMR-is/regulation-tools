const LIST_STYLES = [
  { type: null, label: '1, 2, 3' },
  { type: 'a', label: 'a, b, c' },
  { type: 'A', label: 'A, B, C' },
  { type: 'i', label: 'i, ii, iii' },
  { type: 'I', label: 'I, II, III' },
] as const;

const TABLE_STYLES = [
  { cls: null, label: 'Venjuleg tafla' },
  { cls: 'layout', label: 'Uppsetning (án ramma)' },
  { cls: 'layout layout--list', label: 'Upptalning í töflu' },
] as const;

const useToolbarState = (editor: Editor) =>
  useEditorState({
    editor,
    selector: ({ editor: e }) => ({
      bold: e.isActive('bold'),
      italic: e.isActive('italic'),
      underline: e.isActive('underline'),
      strike: e.isActive('strike'),
      superscript: e.isActive('superscript'),
      subscript: e.isActive('subscript'),
      link: e.isActive('link'),
      align: (e.getAttributes(e.state.selection.$from.parent.type.name).align ||
        null) as string | null,
      bulletList: e.isActive('bulletList'),
      orderedList: e.isActive('orderedList'),
      listType: (e.getAttributes('orderedList').type || null) as string | null,
      inTable: e.isActive('table'),
      tableClass: (e.getAttributes('table').class || null) as string | null,
      blockFormat: currentBlockFormat(e),
      topLevel: atTopLevel(e),
      autogenerated: inAutogenerated(e),
      canUndo: e.can().undo(),
      canRedo: e.can().redo(),
    }),
  });

export const Toolbar = (props: {
  editor: Editor;
  items: Array<ToolbarItem>;
  actions: ToolbarActions;
  /**
   * readOnly/disabled, from the props, which also set the editor's own
   * `isEditable`. That one is not read here: the toolbar's state only
   * updates on a transaction, and changing it makes none.
   */
  disabled?: boolean;
}) => {
  const { editor, actions } = props;
  const s = useToolbarState(editor);
  const chain = () => editor.chain().focus();
  const disabled = !!props.disabled;

  const setAlign = (align: string | null) => {
    const type = editor.state.selection.$from.parent.type.name;
    chain().updateAttributes(type, { align }).run();
  };

  const render = (item: ToolbarItem, key: number): ReactNode => {
    switch (item) {
      case '|':
        return <span key={key} className="regtools-toolbar__separator" />;
      case 'undo':
        return (
          <Button
            key={key}
            label="Afturkalla"
            icon={<Undo2 size={ICON_SIZE} />}
            disabled={disabled || !s.canUndo}
            onClick={() => chain().undo().run()}
          />
        );
      case 'redo':
        return (
          <Button
            key={key}
            label="Endurgera"
            icon={<Redo2 size={ICON_SIZE} />}
            disabled={disabled || !s.canRedo}
            onClick={() => chain().redo().run()}
          />
        );
      case 'bold':
        return (
          <Button
            key={key}
            label="Feitletrað"
            icon={<Bold size={ICON_SIZE} />}
            active={s.bold}
            disabled={disabled}
            onClick={() => chain().toggleBold().run()}
          />
        );
      case 'italic':
        return (
          <Button
            key={key}
            label="Skáletrað"
            icon={<Italic size={ICON_SIZE} />}
            active={s.italic}
            disabled={disabled}
            onClick={() => chain().toggleItalic().run()}
          />
        );
      case 'underline':
        return (
          <Button
            key={key}
            label="Undirstrikað"
            icon={<Underline size={ICON_SIZE} />}
            active={s.underline}
            disabled={disabled}
            onClick={() => chain().toggleUnderline().run()}
          />
        );
      case 'strikethrough':
        return (
          <Button
            key={key}
            label="Yfirstrikað"
            icon={<Strikethrough size={ICON_SIZE} />}
            active={s.strike}
            disabled={disabled}
            onClick={() => chain().toggleStrike().run()}
          />
        );
      case 'superscript':
        return (
          <Button
            key={key}
            label="Hástafur"
            icon={<Superscript size={ICON_SIZE} />}
            active={s.superscript}
            disabled={disabled}
            onClick={() => chain().toggleSuperscript().run()}
          />
        );
      case 'subscript':
        return (
          <Button
            key={key}
            label="Lágstafur"
            icon={<Subscript size={ICON_SIZE} />}
            active={s.subscript}
            disabled={disabled}
            onClick={() => chain().toggleSubscript().run()}
          />
        );
      case 'removeformat':
        return (
          <Button
            key={key}
            label="Hreinsa sniðmát"
            icon={<RemoveFormatting size={ICON_SIZE} />}
            disabled={disabled}
            onClick={() => chain().unsetAllMarks().run()}
          />
        );
      case 'link':
        return (
          <Button
            key={key}
            label="Setja inn/breyta hlekk"
            icon={<Link size={ICON_SIZE} />}
            active={s.link}
            disabled={disabled}
            onClick={() => actions.openDialog('link')}
          />
        );
      case 'alignleft':
        return (
          <Button
            key={key}
            label="Vinstri jöfnun"
            icon={<AlignLeft size={ICON_SIZE} />}
            active={!s.align}
            disabled={disabled}
            onClick={() => setAlign(null)}
          />
        );
      case 'aligncenter':
        return (
          <Button
            key={key}
            label="Miðjað"
            icon={<AlignCenter size={ICON_SIZE} />}
            active={s.align === 'center'}
            disabled={disabled}
            onClick={() => setAlign('center')}
          />
        );
      case 'alignright':
        return (
          <Button
            key={key}
            label="Hægri jöfnun"
            icon={<AlignRight size={ICON_SIZE} />}
            active={s.align === 'right'}
            disabled={disabled}
            onClick={() => setAlign('right')}
          />
        );
      case 'align':
        return (
          <Dropdown
            key={key}
            label="Jöfnun"
            disabled={disabled}
            icon={
              s.align === 'center' ? (
                <AlignCenter size={ICON_SIZE} />
              ) : s.align === 'right' ? (
                <AlignRight size={ICON_SIZE} />
              ) : (
                <AlignLeft size={ICON_SIZE} />
              )
            }
          >
            <MenuItem
              label="Vinstri"
              active={!s.align}
              onClick={() => setAlign(null)}
            />
            <MenuItem
              label="Miðjað"
              active={s.align === 'center'}
              onClick={() => setAlign('center')}
            />
            <MenuItem
              label="Hægri"
              active={s.align === 'right'}
              onClick={() => setAlign('right')}
            />
          </Dropdown>
        );
      case 'bullist':
        return (
          <Button
            key={key}
            label="Punktalisti"
            icon={<List size={ICON_SIZE} />}
            active={s.bulletList}
            disabled={disabled}
            onClick={() => chain().toggleBulletList().run()}
          />
        );
      case 'numlist':
        return (
          <span key={key} className="regtools-toolbar__group">
            <Button
              label="Númeraður listi"
              icon={<ListOrdered size={ICON_SIZE} />}
              active={s.orderedList}
              disabled={disabled}
              onClick={() => chain().toggleOrderedList().run()}
            />
            {s.orderedList && (
              <Dropdown
                label="Tegund númera"
                disabled={disabled}
                icon={
                  <span className="regtools-toolbar__text">
                    {LIST_STYLES.find(
                      (l) => l.type === s.listType,
                    )?.label.split(',')[0] ?? '1'}
                  </span>
                }
              >
                {LIST_STYLES.map((l) => (
                  <MenuItem
                    key={l.label}
                    label={l.label}
                    active={s.listType === l.type}
                    onClick={() =>
                      chain()
                        .updateAttributes('orderedList', { type: l.type })
                        .run()
                    }
                  />
                ))}
              </Dropdown>
            )}
          </span>
        );
      case 'styleselect':
        return (
          <span key={key} className="regtools-toolbar__group">
            {/* A dropdown, not a <select>: a closed <select> changes
                value on every arrow key on Windows, which would apply each
                format passed over ("m. heiti" inserts text). */}
            <Dropdown
              label="Snið"
              disabled={disabled}
              icon={
                <span className="regtools-toolbar__text">
                  {s.blockFormat ? BLOCK_FORMATS[s.blockFormat].label : 'Snið'}
                </span>
              }
            >
              {(Object.keys(BLOCK_FORMATS) as Array<BlockFormat>).map((f) => {
                const format = BLOCK_FORMATS[f];
                const structural = 'structural' in format;
                return (
                  <MenuItem
                    key={f}
                    label={format.label}
                    active={s.blockFormat === f}
                    disabled={structural && !s.topLevel}
                    onClick={() => setBlockFormat(editor, f)}
                  />
                );
              })}
            </Dropdown>
            {s.autogenerated && (
              <Button
                label="Sjálfvirkt myndað: merkja yfirfarið"
                icon={<BadgeCheck size={ICON_SIZE} />}
                disabled={disabled}
                onClick={() => clearAutogenerated(editor)}
              />
            )}
          </span>
        );
      case 'table':
        return (
          <Dropdown
            key={key}
            label="Tafla"
            disabled={disabled}
            icon={<Table size={ICON_SIZE} />}
            active={s.inTable}
          >
            {!s.inTable ? (
              <MenuItem
                label="Setja inn töflu"
                disabled={disabled}
                onClick={() =>
                  chain()
                    .insertTable({ rows: 3, cols: 3, withHeaderRow: false })
                    .run()
                }
              />
            ) : (
              <>
                <MenuItem
                  label="Röð fyrir ofan"
                  onClick={() => chain().addRowBefore().run()}
                />
                <MenuItem
                  label="Röð fyrir neðan"
                  onClick={() => chain().addRowAfter().run()}
                />
                <MenuItem
                  label="Dálkur til vinstri"
                  onClick={() => chain().addColumnBefore().run()}
                />
                <MenuItem
                  label="Dálkur til hægri"
                  onClick={() => chain().addColumnAfter().run()}
                />
                <MenuItem
                  label="Eyða röð"
                  onClick={() => chain().deleteRow().run()}
                />
                <MenuItem
                  label="Eyða dálki"
                  onClick={() => chain().deleteColumn().run()}
                />
                <MenuItem
                  label="Sameina reiti"
                  disabled={!editor.can().mergeCells()}
                  onClick={() => chain().mergeCells().run()}
                />
                <MenuItem
                  label="Skipta reit"
                  disabled={!editor.can().splitCell()}
                  onClick={() => chain().splitCell().run()}
                />
                {TABLE_STYLES.map((t) => (
                  <MenuItem
                    key={t.label}
                    label={t.label}
                    active={s.tableClass === t.cls}
                    onClick={() =>
                      chain().updateAttributes('table', { class: t.cls }).run()
                    }
                  />
                ))}
                <MenuItem
                  label="Eyða töflu"
                  onClick={() => chain().deleteTable().run()}
                />
              </>
            )}
          </Dropdown>
        );
      case 'image':
        return (
          <Button
            key={key}
            label="Setja inn mynd"
            icon={<Image size={ICON_SIZE} />}
            disabled={disabled}
            onClick={actions.insertImage}
          />
        );
      case 'hr':
        return (
          <Button
            key={key}
            label="Lárétt lína"
            icon={<Minus size={ICON_SIZE} />}
            disabled={disabled}
            onClick={() => chain().setHorizontalRule().run()}
          />
        );
      case 'charmap':
        return (
          <Button
            key={key}
            label="Sértákn"
            icon={<Omega size={ICON_SIZE} />}
            disabled={disabled}
            onClick={() => actions.openDialog('charmap')}
          />
        );
      case 'code':
        return (
          <Button
            key={key}
            label="HTML kóði"
            icon={<Code size={ICON_SIZE} />}
            disabled={disabled}
            onClick={() => actions.openDialog('code')}
          />
        );
      case 'searchreplace':
        return (
          <Button
            key={key}
            label="Leita og skipta út"
            icon={<Search size={ICON_SIZE} />}
            onClick={() => actions.openDialog('searchreplace')}
          />
        );
      case 'customInsertButton':
        return (
          <Button
            key={key}
            label="Færa inn Word skjal"
            icon={<FileText size={ICON_SIZE} />}
            disabled={disabled}
            onClick={actions.importWord}
          />
        );
      case 'inlineformat':
      case 'alignment':
      case 'insert': {
        const icons = {
          inlineformat: <Underline size={ICON_SIZE} />,
          alignment: <AlignLeft size={ICON_SIZE} />,
          insert: <Omega size={ICON_SIZE} />,
        };
        const labels = {
          inlineformat: 'Fleiri snið',
          alignment: 'Jöfnun',
          insert: 'Annað',
        };
        return (
          <Dropdown
            key={key}
            label={labels[item]}
            icon={icons[item]}
            disabled={disabled}
          >
            <span className="regtools-toolbar__menurow">
              {GROUPS[item]!.map((sub, i) => render(sub, i))}
            </span>
          </Dropdown>
        );
      }
    }
  };

  return <>{props.items.map(render)}</>;
};
