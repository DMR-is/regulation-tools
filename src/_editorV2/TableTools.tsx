const GRID = 10;

/**
 * Pick a size to insert: hover or arrow keys, then click or Enter. One cell
 * is in the Tab order; the arrows move within the grid.
 */
export const TableSizePicker = (props: {
  onPick: (rows: number, cols: number) => void;
}) => {
  const [size, setSize] = useState({ rows: 3, cols: 3 });
  const grid = useRef<HTMLDivElement>(null);
  const focusCell = (rows: number, cols: number) => {
    setSize({ rows, cols });
    const cell = grid.current?.querySelector<HTMLElement>(
      `[data-cell="${rows}-${cols}"]`,
    );
    cell?.focus();
  };
  return (
    <div className="regtools-tablesize">
      <div
        ref={grid}
        className="regtools-tablesize__grid"
        role="grid"
        aria-label="Stærð töflu"
        onKeyDown={(e) => {
          const move = {
            ArrowRight: [0, 1],
            ArrowLeft: [0, -1],
            ArrowDown: [1, 0],
            ArrowUp: [-1, 0],
          }[e.key];
          if (move) {
            e.preventDefault();
            e.stopPropagation();
            const clamp = (n: number) => Math.min(GRID, Math.max(1, n));
            focusCell(clamp(size.rows + move[0]!), clamp(size.cols + move[1]!));
          }
        }}
      >
        {Array.from({ length: GRID }, (_, r) => (
          <div key={r} role="row" className="regtools-tablesize__row">
            {Array.from({ length: GRID }, (_, c) => {
              const rows = r + 1;
              const cols = c + 1;
              const current = rows === size.rows && cols === size.cols;
              return (
                <button
                  key={c}
                  type="button"
                  role="gridcell"
                  data-cell={`${rows}-${cols}`}
                  className={
                    'regtools-tablesize__cell' +
                    (rows <= size.rows && cols <= size.cols
                      ? ' regtools-tablesize__cell--on'
                      : '')
                  }
                  aria-label={`${rows} × ${cols}`}
                  tabIndex={current ? 0 : -1}
                  onMouseDown={(e) => e.preventDefault()}
                  onMouseEnter={() => setSize({ rows, cols })}
                  onFocus={() => setSize({ rows, cols })}
                  onClick={() => props.onPick(rows, cols)}
                />
              );
            })}
          </div>
        ))}
      </div>
      <span className="regtools-tablesize__label" aria-live="polite">
        {size.rows} {size.rows === 1 ? 'röð' : 'raðir'} × {size.cols}{' '}
        {size.cols === 1 ? 'dálkur' : 'dálkar'}
      </span>
    </div>
  );
};

export const insertTable = (editor: Editor, rows: number, cols: number) =>
  editor
    .chain()
    .focus()
    .insertTable({ rows, cols, withHeaderRow: false })
    .run();

