/**
 * The right-click menu in a table: every table action. Opened by the mouse
 * or the keyboard (the context-menu key, Shift+F10); arrow keys move
 * through it and Escape closes it, back to the text.
 */
export const TableContextMenu = (props: { editor: Editor }) => {
  const { editor } = props;
  const [at, setAt] = useState<{ x: number; y: number }>();
  const menu = useRef<HTMLDivElement>(null);
  const s = useTableState(editor);

  useEffect(() => {
    const dom = editor.view.dom;
    const open = (e: MouseEvent) => {
      if (!editor.isEditable) {
        return;
      }
      const cell = (e.target as Element).closest?.('td, th');
      const view = editor.view;
      if (cell && dom.contains(cell)) {
        // Right-clicking a cell outside the selection moves the cursor
        // there, as in a word processor; inside a cell selection keeps it.
        const inSelection =
          editor.state.selection instanceof CellSelection &&
          cell.classList.contains('selectedCell');
        if (!inSelection) {
          const found = view.posAtCoords({ left: e.clientX, top: e.clientY });
          found && editor.commands.setTextSelection(found.pos);
        }
      } else if (e.clientX || e.clientY || tableAround(editor) == null) {
        return; // not in a table: the browser's own menu
      }
      e.preventDefault();
      let { clientX: x, clientY: y } = e;
      if (!x && !y) {
        // From the keyboard: at the cursor.
        const c = view.coordsAtPos(editor.state.selection.from);
        x = c.left;
        y = c.bottom;
      }
      setAt({ x, y });
    };
    dom.addEventListener('contextmenu', open);
    return () => dom.removeEventListener('contextmenu', open);
  }, [editor]);

  useLayoutEffect(() => {
    const el = menu.current;
    if (!at || !el) {
      return;
    }
    // Keep it on screen.
    const r = el.getBoundingClientRect();
    const x = Math.min(at.x, window.innerWidth - r.width - 8);
    const y = Math.min(at.y, window.innerHeight - r.height - 8);
    el.style.left = Math.max(8, x) + 'px';
    el.style.top = Math.max(8, y) + 'px';
    el.querySelector<HTMLElement>('button:not(:disabled)')?.focus();
  }, [at]);

  useEffect(() => {
    if (!at) {
      return;
    }
    const close = (e: Event) => {
      if (!menu.current?.contains(e.target as Node)) {
        setAt(undefined);
      }
    };
    document.addEventListener('mousedown', close);
    window.addEventListener('scroll', close, true);
    window.addEventListener('blur', close);
    return () => {
      document.removeEventListener('mousedown', close);
      window.removeEventListener('scroll', close, true);
      window.removeEventListener('blur', close);
    };
  }, [at]);

  if (!at || s.table == null) {
    return null;
  }
  return (
    <div
      ref={menu}
      className="regtools-toolbar__menu regtools-contextmenu"
      role="group"
      aria-label="Tafla"
      style={{ left: at.x, top: at.y }}
      onClick={(e) => {
        if ((e.target as Element).closest('button')) {
          setAt(undefined);
        }
      }}
      onKeyDown={(e) => {
        if (e.key === 'Escape' || e.key === 'Tab') {
          e.preventDefault();
          setAt(undefined);
          editor.commands.focus();
        } else if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
          e.preventDefault();
          const items = Array.from(
            menu.current!.querySelectorAll<HTMLElement>(
              'button:not(:disabled)',
            ),
          );
          const i = items.indexOf(document.activeElement as HTMLElement);
          const next =
            e.key === 'ArrowDown'
              ? items[(i + 1) % items.length]
              : items[(i - 1 + items.length) % items.length];
          next?.focus();
        }
      }}
    >
      <TableMenuItems editor={editor} tableClass={s.tableClass} />
    </div>
  );
};
