/*
  Working with tables, as `Editor` offered it: a size grid to insert one,
  the table menu in the toolbar, a bar that floats over the table the
  cursor is in, and a right-click menu. All three menus run the same
  actions (`TABLE_ACTIONS`).

  The floating bar also carries "mark as checked" for a block flagged as
  auto-generated, which used to appear in the toolbar and moved the items
  after it.
*/

import React, {
  Fragment,
  MutableRefObject,
  ReactNode,
  useEffect,
  useLayoutEffect,
  useRef,
  useState,
} from 'react';
import { Editor, useEditorState } from '@tiptap/react';
import { CellSelection } from '@tiptap/pm/tables';
import {
  BadgeCheck,
  Paintbrush,
  TableCellsMerge,
  TableCellsSplit,
  Trash2,
} from 'lucide-react';

import { Button, Dropdown, ICON_SIZE, MenuHeading, MenuItem } from './controls';
import { autogeneratedAncestor, clearAutogenerated } from './extensions';

export const TABLE_STYLES = [
  { cls: null, label: 'Venjuleg tafla' },
  { cls: 'layout', label: 'Uppsetning (án ramma)' },
  { cls: 'layout layout--list', label: 'Upptalning í töflu' },
] as const;

type Chain = ReturnType<Editor['chain']>;

type TableAction = {
  label: string;
  icon?: ReactNode;
  run: (chain: Chain) => Chain;
  can?: (editor: Editor) => boolean;
  danger?: true;
};

const icon = (Icon: typeof Trash2) => <Icon size={ICON_SIZE} />;

/**
 * The actions on the table the cursor is in, in groups. On the bar over the
 * table, a group is a dropdown named by its title, or with `buttons`, a
 * button per action: adding a row above or below looks the same in an
 * empty table, so those are named rather than drawn.
 */
export const TABLE_ACTIONS: Array<{
  title: string;
  buttons?: true;
  actions: Array<TableAction>;
}> = [
  {
    title: 'Raðir',
    actions: [
      { label: 'Röð fyrir ofan', run: (c) => c.addRowBefore() },
      { label: 'Röð fyrir neðan', run: (c) => c.addRowAfter() },
      { label: 'Eyða röð', run: (c) => c.deleteRow(), danger: true },
    ],
  },
  {
    title: 'Dálkar',
    actions: [
      { label: 'Dálkur til vinstri', run: (c) => c.addColumnBefore() },
      { label: 'Dálkur til hægri', run: (c) => c.addColumnAfter() },
      { label: 'Eyða dálki', run: (c) => c.deleteColumn(), danger: true },
    ],
  },
  {
    title: 'Reitir',
    buttons: true,
    actions: [
      {
        label: 'Sameina reiti',
        icon: icon(TableCellsMerge),
        run: (c) => c.mergeCells(),
        can: (e) => e.can().mergeCells(),
      },
      {
        label: 'Skipta reit',
        icon: icon(TableCellsSplit),
        run: (c) => c.splitCell(),
        can: (e) => e.can().splitCell(),
      },
    ],
  },
];

const DELETE_TABLE: TableAction = {
  label: 'Eyða töflu',
  run: (c) => c.deleteTable(),
  danger: true,
};

const run = (editor: Editor, action: TableAction) =>
  action.run(editor.chain().focus()).run();

const setStyle = (editor: Editor, cls: string | null) =>
  editor.chain().focus().updateAttributes('table', { class: cls }).run();

// ---------------------------------------------------------------------------

/** The table the selection is in, innermost first. */
const tableAround = (editor: Editor) => {
  const { $from } = editor.state.selection;
  for (let depth = $from.depth; depth > 0; depth--) {
    if ($from.node(depth).type.name === 'table') {
      return $from.before(depth);
    }
  }
  return undefined;
};

/** The element a node is drawn as (a node view may wrap the <table>). */
const elementAt = (editor: Editor, pos: number) => {
  const dom = editor.view.nodeDOM(pos);
  if (!(dom instanceof HTMLElement)) {
    return undefined;
  }
  const isTable = editor.state.doc.nodeAt(pos)?.type.name === 'table';
  return isTable && dom.tagName !== 'TABLE'
    ? (dom.querySelector('table') as HTMLElement | null) || dom
    : dom;
};

