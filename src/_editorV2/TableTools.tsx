/** Whether the cursor's cell spans more than one row or column. */
const inSpanningCell = (editor: Editor) => {
  const { $from } = editor.state.selection;
  for (let depth = $from.depth; depth > 0; depth--) {
    const { type, attrs } = $from.node(depth);
    if (type.name === 'tableCell' || type.name === 'tableHeader') {
      return attrs.colspan > 1 || attrs.rowspan > 1;
    }
  }
  return false;
};

/**
 * What the bar and the right-click menu show. The selector runs on every
 * transaction, keystrokes included, so it is kept cheap; the components
 * re-render only when one of these values changes, not on every keystroke.
 */
const useTableState = (editor: Editor) =>
  useEditorState({
    editor,
    selector: ({ editor: e }) => {
      const table = tableAround(e);
      const cells = e.state.selection instanceof CellSelection;
      return {
        table,
        tableClass:
          table == null
            ? null
            : ((e.getAttributes('table').class || null) as string | null),
        // Not read directly: they re-render the bar when merging or
        // splitting becomes possible, for the `can` checks of TABLE_ACTIONS.
        // Only asked when it could be so: `can()` is a dry run of the
        // command, too much for every keystroke in a cell.
        canMerge: cells && e.can().mergeCells(),
        canSplit: (cells || inSpanningCell(e)) && e.can().splitCell(),
      };
    },
  });

const useContextState = (editor: Editor) => {
  const table = useTableState(editor);
  const rest = useEditorState({
    editor,
    selector: ({ editor: e }) => ({
      focused: e.isFocused,
      editable: e.isEditable,
      flagged: autogeneratedAncestor(e)?.pos,
    }),
  });
  return { ...table, ...rest };
};

/** The visible part of the page an element is scrolled within. */
const clipRect = (el: HTMLElement) => {
  let top = 0;
  let left = 0;
  let bottom = window.innerHeight;
  let right = window.innerWidth;
  for (let p = el.parentElement; p; p = p.parentElement) {
    const { overflowX, overflowY } = getComputedStyle(p);
    if (overflowX !== 'visible' || overflowY !== 'visible') {
      const r = p.getBoundingClientRect();
      top = Math.max(top, r.top);
      left = Math.max(left, r.left);
      bottom = Math.min(bottom, r.bottom);
      right = Math.min(right, r.right);
    }
  }
  return { top, left, bottom, right };
};

const GAP = 6;

/**
 * A bar above the table the cursor is in (and above a block flagged as
 * auto-generated). It stays in view under the toolbar while the table is
 * scrolled through, and hides once the table is out of view.
 */
export const ContextBar = (props: {
  editor: Editor;
  toolbarRef: MutableRefObject<HTMLElement | null>;
  tables: boolean;
  autogenerated: boolean;
}) => {
  const { editor } = props;
  const s = useContextState(editor);
  const bar = useRef<HTMLDivElement>(null);
  const [hasFocus, setHasFocus] = useState(false);
  const [position, setPosition] = useState<{ top: number; left: number }>();

  const table = props.tables ? s.table : undefined;
  const flagged = props.autogenerated ? s.flagged : undefined;
  // The innermost of the two is the one the bar sits over.
  const anchor =
    table != null && (flagged == null || table > flagged) ? table : flagged;
  const shown = s.editable && anchor != null && (s.focused || hasFocus);

  useLayoutEffect(() => {
    if (!shown) {
      setPosition(undefined);
      return;
    }
    let frame = 0;
    const place = () => {
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(() => {
        const target = elementAt(editor, anchor!);
        const el = bar.current;
        if (!target || !el) {
          return;
        }
        const t = target.getBoundingClientRect();
        const clip = clipRect(target);
        const toolbar = props.toolbarRef.current?.getBoundingClientRect();
        const ceiling = Math.max(
          clip.top,
          toolbar && toolbar.bottom > 0 ? toolbar.bottom : 0,
        );
        const height = el.offsetHeight;
        if (t.bottom < ceiling || t.top > clip.bottom) {
          setPosition(undefined); // scrolled out of view
          return;
        }
        // Above the block, else below it; a block taller than the view,
        // scrolled into, has it under the toolbar.
        const above = t.top - height - GAP;
        const below = t.bottom + GAP;
        const top =
          above >= ceiling + GAP
            ? above
            : below + height <= clip.bottom - GAP
            ? below
            : ceiling + GAP;
        const left = Math.max(
          clip.left,
          Math.min(t.left, clip.right - el.offsetWidth),
        );
        setPosition((p) =>
          p && p.top === top && p.left === left ? p : { top, left },
        );
      });
    };
    place();
    window.addEventListener('scroll', place, true);
    window.addEventListener('resize', place);
    // The text changing size moves the table (a row added, a line wrapping
    // in a cell). Watched this way rather than per keystroke: the observer
    // runs after layout, and only when a size did change.
    const observer = new ResizeObserver(place);
    observer.observe(editor.view.dom);
    const target = elementAt(editor, anchor!);
    target && observer.observe(target);
    return () => {
      cancelAnimationFrame(frame);
      window.removeEventListener('scroll', place, true);
      window.removeEventListener('resize', place);
      observer.disconnect();
    };
  }, [shown, anchor, editor, props.toolbarRef]);

  if (!shown) {
    return null;
  }
  return (
    <div
      ref={bar}
      className="regtools-contextbar"
      role="toolbar"
      aria-label={table != null ? 'Tafla' : 'Sjálfvirkt myndað'}
      style={
        position
          ? { top: position.top, left: position.left }
          : { visibility: 'hidden' }
      }
      onFocus={() => setHasFocus(true)}
      onBlur={(e) => {
        if (!bar.current?.contains(e.relatedTarget as Node | null)) {
          setHasFocus(false);
        }
      }}
    >
      {flagged != null && (
        <button
          type="button"
          className="regtools-toolbar__button regtools-contextbar__check"
          onMouseDown={(e) => e.preventDefault()}
          onClick={() => clearAutogenerated(editor)}
        >
          <BadgeCheck size={ICON_SIZE} aria-hidden />
          Sjálfvirkt myndað: merkja yfirfarið
        </button>
      )}
      {flagged != null && table != null && (
        <span className="regtools-toolbar__separator" />
      )}
      {table != null && (
        <>
          {TABLE_ACTIONS.map((group) =>
            group.buttons ? (
              <Fragment key={group.title}>
                <span className="regtools-toolbar__separator" />
                {group.actions.map((a) => (
                  <Button
                    key={a.label}
                    label={a.label}
                    icon={a.icon}
                    disabled={a.can && !a.can(editor)}
                    onClick={() => run(editor, a)}
                  />
                ))}
              </Fragment>
            ) : (
              <Dropdown
                key={group.title}
                label={group.title}
                icon={
                  <span className="regtools-toolbar__text">{group.title}</span>
                }
              >
                {group.actions.map((a) => (
                  <MenuItem
                    key={a.label}
                    label={a.label}
                    danger={a.danger}
                    disabled={a.can && !a.can(editor)}
                    onClick={() => run(editor, a)}
                  />
                ))}
              </Dropdown>
            ),
          )}
          <span className="regtools-toolbar__separator" />
          <Dropdown label="Útlit töflu" icon={<Paintbrush size={ICON_SIZE} />}>
            {TABLE_STYLES.map((t) => (
              <MenuItem
                key={t.label}
                label={t.label}
                active={s.tableClass === t.cls}
                onClick={() => setStyle(editor, t.cls)}
              />
            ))}
          </Dropdown>
          <Button
            label={DELETE_TABLE.label}
            icon={<Trash2 size={ICON_SIZE} />}
            onClick={() => run(editor, DELETE_TABLE)}
          />
        </>
      )}
    </div>
  );
};

