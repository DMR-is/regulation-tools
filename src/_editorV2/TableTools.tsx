/** Every table action, under headings: the toolbar's and the right-click
 * menu. */
export const TableMenuItems = (props: {
  editor: Editor;
  tableClass: string | null;
}) => {
  const { editor } = props;
  return (
    <>
      {TABLE_ACTIONS.map((group) => (
        <Fragment key={group.title}>
          <MenuHeading>{group.title}</MenuHeading>
          {group.actions.map((a) => (
            <MenuItem
              key={a.label}
              label={a.label}
              danger={a.danger}
              disabled={a.can && !a.can(editor)}
              onClick={() => run(editor, a)}
            />
          ))}
        </Fragment>
      ))}
      <MenuHeading>Útlit</MenuHeading>
      {TABLE_STYLES.map((t) => (
        <MenuItem
          key={t.label}
          label={t.label}
          active={props.tableClass === t.cls}
          onClick={() => setStyle(editor, t.cls)}
        />
      ))}
      <span className="regtools-toolbar__menuseparator" />
      <MenuItem
        label={DELETE_TABLE.label}
        danger
        onClick={() => run(editor, DELETE_TABLE)}
      />
    </>
  );
};

