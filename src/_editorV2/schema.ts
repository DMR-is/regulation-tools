// Tables

/*
  Tables keep their markup as TinyMCE did: every attribute (`width`,
  `border`, `valign`, `cellpadding`, `style`, …), `<colgroup>`, and which
  rows are in `<thead>` and `<tfoot>`. Cleanup removes all but a few of
  them from a regulation on save, but apps that store the editor's output
  as it is (ojoi's adverts) keep them, and they set how a table prints.
*/

/** The table elements' attributes that a node attribute of its own holds. */
const MODELLED = ['id', 'data-autogenerated', 'class', 'colspan', 'rowspan'];

/**
 * The rest of an element's attributes, verbatim. Event handlers (`on…`)
 * are left out. A cell's `text-align` belongs to its `align` attribute, as
 * on every block, so the alignment buttons change it.
 */
const otherAttributes = (modelled: Array<string>): Attribute => ({
  default: null,
  parseHTML: (elm) => {
    let attrs: Record<string, string> | null = null;
    for (const { name, value } of Array.from(elm.attributes)) {
      if (modelled.includes(name) || name.startsWith('on')) {
        continue;
      }
      const kept =
        name === 'style' && modelled.includes('align')
          ? withoutTextAlign(value)
          : value;
      // Empty values are kept (`nowrap=""`), but not a style that held
      // only `text-align`.
      if (kept || name !== 'style') {
        (attrs ||= {})[name] = kept;
      }
    }
    return attrs;
  },
  renderHTML: (attrs) => (attrs.other as Record<string, string> | null) || {},
});

const withoutTextAlign = (style: string) =>
  style
    .split(';')
    .filter((decl) => decl.trim() && !/^\s*text-align\s*:/i.test(decl))
    .join(';')
    .trim();

type ColGroup = {
  attrs: Record<string, string>;
  cols: Array<Record<string, string>>;
};

const attributesOf = (elm: Element) =>
  Object.fromEntries(Array.from(elm.attributes, (a) => [a.name, a.value]));

const RegulationTable = Table.extend({
  addAttributes() {
    return {
      class: htmlAttr('class'),
      other: otherAttributes(MODELLED),
      colgroups: {
        default: null,
        rendered: false,
        parseHTML: (elm): Array<ColGroup> | null => {
          const groups = Array.from(elm.children)
            .filter((child) => child.tagName === 'COLGROUP')
            .map((group) => ({
              attrs: attributesOf(group),
              cols: Array.from(group.children, attributesOf),
            }));
          return groups.length ? groups : null;
        },
      },
    };
  },
  renderHTML({ node, HTMLAttributes }) {
    const colgroups = (node.attrs.colgroups as Array<ColGroup> | null) || [];
    return [
      'table',
      HTMLAttributes,
      ...colgroups.map(
        ({ attrs, cols }): DOMOutputSpec => [
          'colgroup',
          attrs,
          ...cols.map((col): DOMOutputSpec => ['col', col]),
        ],
      ),
      // All rows are in the `<tbody>` here; the serializer moves the head
      // and foot rows back out (`regroupTableSections`).
      ['tbody', 0],
    ];
  },
}).configure({ resizable: false });

/**
 * Marks a row that was in a `<thead>` or `<tfoot>`. A row added in the
 * editor has none.
 */
export const ROW_SECTION = 'data-regtools-section';

const RegulationTableRow = TableRow.extend({
  addAttributes() {
    return {
      other: otherAttributes(MODELLED),
      section: {
        default: null,
        parseHTML: (elm) => {
          const tag = elm.parentElement?.tagName;
          return tag === 'THEAD' ? 'head' : tag === 'TFOOT' ? 'foot' : null;
        },
        renderHTML: (attrs) =>
          attrs.section ? { [ROW_SECTION]: attrs.section as string } : {},
      },
    };
  },
});

/**
 * Tiptap's `colwidth` is for its column resizing, which is off, and it
 * wrote a `colwidth` HTML attribute. Never read or written: widths are in
 * the cells' own attributes and the `<colgroup>`. (Tiptap's parse of it
 * also searched the whole table once per cell: seconds on a large table.)
 */
const cellAttributes = (
  parent: Record<string, Attribute> | undefined,
  modelled: Array<string>,
): Record<string, Attribute> => ({
  ...parent,
  colwidth: { default: null, rendered: false, parseHTML: () => null },
  other: otherAttributes([...MODELLED, 'align', ...modelled]),
});

const RegulationTableCell = TableCell.extend({
  addAttributes() {
    return cellAttributes(this.parent?.(), []);
  },
});

/** `scope` on header cells, which cleanup keeps. */
const RegulationTableHeader = TableHeader.extend({
  addAttributes() {
    return {
      ...cellAttributes(this.parent?.(), ['scope']),
      scope: htmlAttr('scope'),
    };
  },
});

