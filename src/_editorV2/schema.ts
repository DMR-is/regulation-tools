// Blocks

/**
 * Paragraph variants are classes (`indented`, `Dags`, `FHUndirskr`,
 * `Undirritun`, …), kept as written. Legacy indents are `margin-left` and
 * `text-indent` styles, which cleanup keeps on paragraphs.
 */
const RegulationParagraph = Paragraph.extend({
  addAttributes() {
    return {
      ...this.parent?.(),
      class: htmlAttr('class'),
      indent: {
        default: null,
        parseHTML: (elm) => {
          const { marginLeft, textIndent } = elm.style;
          return marginLeft || textIndent
            ? `${marginLeft}|${textIndent}`
            : null;
        },
        renderHTML: (attrs) => {
          if (!attrs.indent) {
            return {};
          }
          const [marginLeft, textIndent] = (attrs.indent as string).split('|');
          return {
            style: [
              marginLeft && `margin-left: ${marginLeft}`,
              textIndent && `text-indent: ${textIndent}`,
            ]
              .filter(Boolean)
              .join('; '),
          };
        },
      },
    };
  },
});

/** Plain headings, `h1`–`h6`, outside the regulation's structure. */
const Heading = Node.create({
  name: 'heading',
  group: 'block',
  content: 'inline*',
  defining: true,
  addAttributes() {
    return {
      level: {
        default: 3,
        parseHTML: (elm) => Number(elm.tagName[1]),
        rendered: false,
      },
    };
  },
  parseHTML() {
    return [1, 2, 3, 4, 5, 6].map((level) => ({ tag: `h${level}` }));
  },
  renderHTML({ node, HTMLAttributes }) {
    return [`h${node.attrs.level as number}`, HTMLAttributes, 0];
  },
});

/**
 * A heading in the regulation's structure: `<h3 class="article__title">`
 * and its kin. Only at the top level of the text, as `nonRoot*Titles` in
 * useTextWarnings requires. Its name is an `<em>` inside it, which cleanup
 * gives the right class (`article__name`, …) on save.
 */
const structuralHeading = (
  name: string,
  tag: 'h2' | 'h3',
  className: string,
  /** The class values cleanup keeps for it. Default: `className` alone. */
  classes: Array<string> = [className],
) =>
  Node.create({
    name,
    // Also `block`, so a stored text with a title inside a list or cell
    // loads unchanged: loading never restructures a text. The editor's
    // commands only create titles at the top level (`atTopLevel`), and the
    // nonRoot*Titles warnings point out any that are not.
    group: 'block structure',
    content: 'inline*',
    defining: true,
    parseHTML() {
      // Before plain headings, which would otherwise take these too. Only
      // the exact class values cleanup keeps: for any other class string
      // cleanup drops the class (`removeUnwantedAttributes`), so this is
      // then a plain heading, as it is when Editor saves it.
      return [
        {
          tag,
          priority: 60,
          getAttrs: (elm) =>
            classes.includes(
              (elm.getAttribute('class') || '').trim().replace(/\s+/g, ' '),
            ) && null,
        },
      ];
    },
    renderHTML({ HTMLAttributes }) {
      return [tag, mergeAttributes({ class: className }, HTMLAttributes), 0];
    },
  });

/** Grein. `provisional` is Bráðabirgðaákvæði (`article__title--provisional`). */
const ArticleTitle = structuralHeading('articleTitle', 'h3', 'article__title', [
  'article__title',
  'article__title article__title--provisional',
]).extend({
  addAttributes() {
    return {
      provisional: {
        default: false,
        parseHTML: (elm) =>
          elm.classList.contains('article__title--provisional'),
        renderHTML: (attrs) =>
          attrs.provisional ? { class: 'article__title--provisional' } : {},
      },
    };
  },
});
/** Kafli */
const ChapterTitle = structuralHeading('chapterTitle', 'h2', 'chapter__title');
/** Undirkafli */
const SubchapterTitle = structuralHeading(
  'subchapterTitle',
  'h2',
  'subchapter__title',
);
const SectionTitle = structuralHeading('sectionTitle', 'h2', 'section__title');
const AppendixTitle = structuralHeading(
  'appendixTitle',
  'h2',
  'appendix__title',
);

