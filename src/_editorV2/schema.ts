// Lists

/** `start` and `type` kept exactly as written, `start="1"` included. */
const RegulationOrderedList = OrderedList.extend({
  addAttributes() {
    return {
      start: htmlAttr('start'),
      type: {
        default: null,
        parseHTML: (elm) => elm.getAttribute('type'),
        renderHTML: (attrs) =>
          attrs.type ? { type: attrs.type as string } : {},
      },
    };
  },
  renderHTML({ HTMLAttributes }) {
    return ['ol', HTMLAttributes, 0];
  },
});

const RegulationBulletList = BulletList.extend({
  addAttributes() {
    return {
      start: htmlAttr('start'),
      type: htmlAttr('type'),
    };
  },
});

/**
 * Any block may come first: real texts have list items that hold only a
 * nested list (`<li><ol type="a">…</ol></li>`), which Tiptap's
 * `paragraph block*` would split out of the item.
 */
const RegulationListItem = ListItem.extend({
  content: 'block+',
  addAttributes() {
    return { value: unique(htmlAttr('value')) };
  },
});

