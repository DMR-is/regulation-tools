// Inline

/** `<sup class="footnote-reference">` and `<sup class="footnote__marker">`. */
const RegulationSuperscript = Superscript.extend({
  addAttributes() {
    return { ...this.parent?.(), class: htmlAttr('class') };
  },
});

/**
 * `<sup class="footnote__marker">`, which wraps a footnote's own
 * `<sup class="footnote-reference">`. A mark type of its own, as one mark
 * type cannot be nested in itself.
 */
const FootnoteMarker = Mark.create({
  name: 'footnoteMarker',
  parseHTML() {
    return [{ tag: 'sup.footnote__marker', priority: 60 }];
  },
  renderHTML({ HTMLAttributes }) {
    return [
      'sup',
      mergeAttributes({ class: 'footnote__marker' }, HTMLAttributes),
      0,
    ];
  },
});

/**
 * `<a id="…">` without `href`: an anchor that links point to (footnotes).
 * The Link mark only takes `a[href]`.
 */
const Anchor = Mark.create({
  name: 'anchor',
  inclusive: false,
  // Not together with a link, which would save as nested <a>s and lose the
  // anchor on the next load; a link carries its own `id`.
  excludes: 'link',
  addAttributes() {
    return { id: htmlAttr('id') };
  },
  parseHTML() {
    return [{ tag: 'a[id]:not([href])' }];
  },
  renderHTML({ HTMLAttributes }) {
    return ['a', HTMLAttributes, 0];
  },
});

/**
 * `<span data-cfemail>`: an e-mail address Cloudflare obfuscated in texts
 * copied from the web. Cleanup keeps it, and useTextWarnings points it out
 * (`cfEmailMarkers`), so it is kept whole, as an atom, for the editor to
 * fix by hand.
 */
const CfEmail = Node.create({
  name: 'cfEmail',
  group: 'inline',
  inline: true,
  atom: true,
  addAttributes() {
    return {
      cfemail: htmlAttrAs('cfemail', 'data-cfemail'),
      class: htmlAttr('class'),
      text: {
        default: '',
        parseHTML: (elm) => elm.textContent,
        rendered: false,
      },
    };
  },
  parseHTML() {
    return [{ tag: 'span[data-cfemail]' }];
  },
  renderHTML({ node, HTMLAttributes }) {
    return ['span', HTMLAttributes, node.attrs.text as string];
  },
});

/**
 * `<span data-legacy-indenter>`: runs of spaces from old texts, which
 * cleanup collapses and restores (`flagIndents` / `rehydrateIndents`).
 * Kept whole, as an atom.
 */
const LegacyIndenter = Node.create({
  name: 'legacyIndenter',
  group: 'inline',
  inline: true,
  atom: true,
  addAttributes() {
    return {
      value: {
        default: '',
        parseHTML: (elm) => elm.getAttribute('data-legacy-indenter'),
        renderHTML: (attrs) => ({
          'data-legacy-indenter': attrs.value as string,
        }),
      },
      text: {
        default: ' ',
        parseHTML: (elm) => elm.textContent,
        rendered: false,
      },
    };
  },
  parseHTML() {
    return [{ tag: 'span[data-legacy-indenter]' }];
  },
  renderHTML({ node, HTMLAttributes }) {
    return ['span', HTMLAttributes, node.attrs.text as string];
  },
});

