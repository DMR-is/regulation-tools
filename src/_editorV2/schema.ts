// Attribute helpers

/** An attribute read from, and written back to, one HTML attribute verbatim. */
const htmlAttr = (name: string): Attribute => ({
  default: null,
  parseHTML: (elm) => elm.getAttribute(name),
  renderHTML: (attrs) => {
    const value = attrs[name] as string | null;
    return value == null ? {} : { [name]: value };
  },
});

/**
 * For attributes that identify one element: Enter must not copy them into
 * the new block (Tiptap's default), or `<li value="5">` gives two items
 * numbered 5 and an `id` anchors two places.
 */
const unique = (attr: Attribute): Attribute => ({
  ...attr,
  keepOnSplit: false,
});

/** Under an attribute name that differs from the HTML attribute's. */
const htmlAttrAs = (key: string, name: string): Attribute => ({
  default: null,
  parseHTML: (elm) => elm.getAttribute(name),
  renderHTML: (attrs) => {
    const value = attrs[key] as string | null;
    return value == null ? {} : { [name]: value };
  },
});

/**
 * `align="…"` or `text-align: …`. The editor sets center and right (left is
 * no alignment); a stored `left` or `justify` is kept, as TinyMCE kept it.
 * Cleanup keeps only center and right in a regulation.
 */
const ALIGNMENTS = ['left', 'center', 'right', 'justify'];
const alignAttr: Attribute = {
  default: null,
  parseHTML: (elm) => {
    const value = (
      elm.getAttribute('align') ||
      elm.style.textAlign ||
      ''
    ).toLowerCase();
    return ALIGNMENTS.includes(value) ? value : null;
  },
  renderHTML: (attrs) =>
    attrs.align ? { style: `text-align: ${attrs.align as string}` } : {},
};

const BLOCK_TYPES = [
  'paragraph',
  'heading',
  'articleTitle',
  'chapterTitle',
  'subchapterTitle',
  'sectionTitle',
  'appendixTitle',
  'blockquote',
  'bulletList',
  'orderedList',
  'listItem',
  'table',
  'tableRow',
  'tableCell',
  'tableHeader',
  'horizontalRule',
  'image',
];

/**
 * `id` is allowed on any element (links may point to it), and
 * `data-autogenerated` flags content dirtyClean generated, for the editor
 * to show; cleanup removes it on save.
 */
const GlobalAttributes = Extension.create({
  name: 'regulationGlobalAttributes',
  addGlobalAttributes() {
    return [
      {
        types: BLOCK_TYPES,
        attributes: {
          id: unique(htmlAttr('id')),
          autogenerated: unique(
            htmlAttrAs('autogenerated', 'data-autogenerated'),
          ),
        },
      },
      {
        types: [
          'bold',
          'italic',
          'underline',
          'superscript',
          'subscript',
          'link',
          'footnoteMarker',
        ],
        attributes: { id: unique(htmlAttr('id')) },
      },
      {
        // Cleanup removes align from article, chapter, subchapter and section
        // titles, but keeps it on appendix titles.
        types: [
          'paragraph',
          'heading',
          'tableCell',
          'tableHeader',
          'appendixTitle',
        ],
        attributes: { align: alignAttr },
      },
    ];
  },
});

