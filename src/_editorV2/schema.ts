/*
  The document schema of editor v2, as Tiptap extensions.

  It covers what the stored regulation format can hold: everything
  `cleanupEditorOutput` keeps (its attribute allow-list in
  `_cleanup/cleanup-utils.ts`, `removeUnwantedAttributes`), checked against
  the corpus census in docs/plan-tiptap-editor.md, "Schema". What the schema
  does not describe, ProseMirror drops on load, so every addition here is
  measured by the fidelity check (`./fidelity.ts`) over the corpus.

  The output is meant to go through `cleanupEditorOutput` before it is saved,
  as the current editor's output does. So it is written the way TinyMCE
  wrote it (alignment as `text-align` styles, which cleanup turns back into
  `align`), and it may differ from the stored text in ways cleanup undoes,
  such as a lone `<p>` inside a list item or table cell.

  The regulation's structure is modelled as node types: an article title is
  an `articleTitle` node, not an `h3` that happens to have a class, so the
  editor can tell what it is and where it may go. Paragraph variants that are
  only styling (Dags, FHUndirskr, …) are a class on an ordinary paragraph.
*/

