// ---------------------------------------------------------------------------
// Attribute helpers

/** An attribute read from, and written back to, one HTML attribute verbatim. */
const htmlAttr = (name: string): Attribute => ({
  default: null,
  parseHTML: (elm) => elm.getAttribute(name),
  renderHTML: (attrs) => {
    const value = attrs[name] as string | null;
    return value == null ? {} : { [name]: value };
  },
});

/** Under an attribute name that differs from the HTML attribute's. */
const htmlAttrAs = (key: string, name: string): Attribute => ({
  default: null,
  parseHTML: (elm) => elm.getAttribute(name),
  renderHTML: (attrs) => {
    const value = attrs[key] as string | null;
    return value == null ? {} : { [name]: value };
  },
});

/** `align="center|right"` or `text-align: center|right`; left is the default. */
const alignAttr: Attribute = {
  default: null,
  parseHTML: (elm) => {
    const value = (
      elm.getAttribute('align') ||
      elm.style.textAlign ||
      ''
    ).toLowerCase();
    return value === 'center' || value === 'right' ? value : null;
  },
  renderHTML: (attrs) =>
    attrs.align ? { style: `text-align: ${attrs.align as string}` } : {},
};

const BLOCK_TYPES = [
  'paragraph',
  'heading',
  'articleTitle',
  'chapterTitle',
  'subchapterTitle',
  'sectionTitle',
  'appendixTitle',
  'blockquote',
  'bulletList',
  'orderedList',
  'listItem',
  'table',
  'tableRow',
  'tableCell',
  'tableHeader',
  'horizontalRule',
  'image',
];

/**
 * `id` is allowed on any element (links may point to it), and
 * `data-autogenerated` flags content dirtyClean generated, for the editor
 * to show; cleanup removes it on save.
 */
const GlobalAttributes = Extension.create({
  name: 'regulationGlobalAttributes',
  addGlobalAttributes() {
    return [
      {
        types: BLOCK_TYPES,
        attributes: {
          id: htmlAttr('id'),
          autogenerated: htmlAttrAs('autogenerated', 'data-autogenerated'),
        },
      },
      {
        types: ['bold', 'italic', 'underline', 'superscript', 'subscript'],
        attributes: { id: htmlAttr('id') },
      },
      {
        types: ['paragraph', 'heading', 'tableCell', 'tableHeader'],
        attributes: { align: alignAttr },
      },
    ];
  },
});

// ---------------------------------------------------------------------------
// Blocks

/**
 * Paragraph variants are classes (`indented`, `Dags`, `FHUndirskr`,
 * `Undirritun`, …), kept as written. Legacy indents are `margin-left` and
 * `text-indent` styles, which cleanup keeps on paragraphs.
 */
const RegulationParagraph = Paragraph.extend({
  addAttributes() {
    return {
      ...this.parent?.(),
      class: htmlAttr('class'),
      indent: {
        default: null,
        parseHTML: (elm) => {
          const { marginLeft, textIndent } = elm.style;
          return marginLeft || textIndent
            ? `${marginLeft}|${textIndent}`
            : null;
        },
        renderHTML: (attrs) => {
          if (!attrs.indent) {
            return {};
          }
          const [marginLeft, textIndent] = (attrs.indent as string).split('|');
          return {
            style: [
              marginLeft && `margin-left: ${marginLeft}`,
              textIndent && `text-indent: ${textIndent}`,
            ]
              .filter(Boolean)
              .join('; '),
          };
        },
      },
    };
  },
});

/** Plain headings, `h1`–`h6`, outside the regulation's structure. */
const Heading = Node.create({
  name: 'heading',
  group: 'block',
  content: 'inline*',
  defining: true,
  addAttributes() {
    return {
      level: {
        default: 3,
        parseHTML: (elm) => Number(elm.tagName[1]),
        rendered: false,
      },
    };
  },
  parseHTML() {
    return [1, 2, 3, 4, 5, 6].map((level) => ({ tag: `h${level}` }));
  },
  renderHTML({ node, HTMLAttributes }) {
    return [`h${node.attrs.level as number}`, HTMLAttributes, 0];
  },
});

/**
 * A heading in the regulation's structure: `<h3 class="article__title">`
 * and its kin. Only at the top level of the text, as `nonRoot*Titles` in
 * useTextWarnings requires. Its name is an `<em>` inside it, which cleanup
 * gives the right class (`article__name`, …) on save.
 */
const structuralHeading = (name: string, tag: 'h2' | 'h3', className: string) =>
  Node.create({
    name,
    group: 'block structure',
    content: 'inline*',
    defining: true,
    parseHTML() {
      // Before plain headings, which would otherwise take these too.
      return [{ tag: `${tag}.${className}`, priority: 60 }];
    },
    renderHTML({ HTMLAttributes }) {
      return [tag, mergeAttributes({ class: className }, HTMLAttributes), 0];
    },
  });

/** Grein. `provisional` is Bráðabirgðaákvæði (`article__title--provisional`). */
const ArticleTitle = structuralHeading(
  'articleTitle',
  'h3',
  'article__title',
).extend({
  addAttributes() {
    return {
      provisional: {
        default: false,
        parseHTML: (elm) =>
          elm.classList.contains('article__title--provisional'),
        renderHTML: (attrs) =>
          attrs.provisional ? { class: 'article__title--provisional' } : {},
      },
    };
  },
});
/** Kafli */
const ChapterTitle = structuralHeading('chapterTitle', 'h2', 'chapter__title');
/** Undirkafli */
const SubchapterTitle = structuralHeading(
  'subchapterTitle',
  'h2',
  'subchapter__title',
);
const SectionTitle = structuralHeading('sectionTitle', 'h2', 'section__title');
const AppendixTitle = structuralHeading(
  'appendixTitle',
  'h2',
  'appendix__title',
);

// ---------------------------------------------------------------------------
// Lists

/** `start` and `type` kept exactly as written, `start="1"` included. */
const RegulationOrderedList = OrderedList.extend({
  addAttributes() {
    return {
      start: htmlAttr('start'),
      type: {
        default: null,
        parseHTML: (elm) => elm.getAttribute('type'),
        renderHTML: (attrs) =>
          attrs.type ? { type: attrs.type as string } : {},
      },
    };
  },
  renderHTML({ HTMLAttributes }) {
    return ['ol', HTMLAttributes, 0];
  },
});

const RegulationBulletList = BulletList.extend({
  addAttributes() {
    return {
      start: htmlAttr('start'),
      type: htmlAttr('type'),
    };
  },
});

/**
 * Any block may come first: real texts have list items that hold only a
 * nested list (`<li><ol type="a">…</ol></li>`), which Tiptap's
 * `paragraph block*` would split out of the item.
 */
const RegulationListItem = ListItem.extend({
  content: 'block+',
  addAttributes() {
    return { value: htmlAttr('value') };
  },
});

// ---------------------------------------------------------------------------
// Tables

/**
 * Only `<table><tbody>`, as stored: Tiptap's own table writes a `<colgroup>`
 * and width styles. `class` is `layout` or `layout layout--list`.
 */
const RegulationTable = Table.extend({
  addAttributes() {
    return { class: htmlAttr('class') };
  },
  renderHTML({ HTMLAttributes }) {
    return ['table', HTMLAttributes, ['tbody', 0]];
  },
}).configure({ resizable: false });

/** `scope` on header cells, which cleanup keeps. */
const RegulationTableHeader = TableHeader.extend({
  addAttributes() {
    return { ...this.parent?.(), scope: htmlAttr('scope') };
  },
});

// ---------------------------------------------------------------------------
// Inline

/** `<sup class="footnote-reference">` and `<sup class="footnote__marker">`. */
const RegulationSuperscript = Superscript.extend({
  addAttributes() {
    return { ...this.parent?.(), class: htmlAttr('class') };
  },
});

/**
 * `<sup class="footnote__marker">`, which wraps a footnote's own
 * `<sup class="footnote-reference">`. A mark type of its own, as one mark
 * type cannot be nested in itself.
 */
const FootnoteMarker = Mark.create({
  name: 'footnoteMarker',
  parseHTML() {
    return [{ tag: 'sup.footnote__marker', priority: 60 }];
  },
  renderHTML({ HTMLAttributes }) {
    return [
      'sup',
      mergeAttributes({ class: 'footnote__marker' }, HTMLAttributes),
      0,
    ];
  },
});

/**
 * `<span data-legacy-indenter>`: runs of spaces from old texts, which
 * cleanup collapses and restores (`flagIndents` / `rehydrateIndents`).
 * Kept whole, as an atom.
 */
const LegacyIndenter = Node.create({
  name: 'legacyIndenter',
  group: 'inline',
  inline: true,
  atom: true,
  addAttributes() {
    return {
      value: {
        default: '',
        parseHTML: (elm) => elm.getAttribute('data-legacy-indenter'),
        renderHTML: (attrs) => ({
          'data-legacy-indenter': attrs.value as string,
        }),
      },
      text: {
        default: ' ',
        parseHTML: (elm) => elm.textContent,
        rendered: false,
      },
    };
  },
  parseHTML() {
    return [{ tag: 'span[data-legacy-indenter]' }];
  },
  renderHTML({ node, HTMLAttributes }) {
    return ['span', HTMLAttributes, node.attrs.text as string];
  },
});

